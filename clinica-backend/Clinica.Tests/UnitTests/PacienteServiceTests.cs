using Clinica.Application.DTOs;
using Clinica.Application.Services;
using Clinica.Domain.Entities;
using Clinica.Domain.Interfaces;
using FluentAssertions;
using Moq;

namespace Clinica.Tests.UnitTests
{
    public class PacienteServiceTests
    {
        // O Mock é um "Ator" que vai fingir ser o Repositório
        private readonly Mock<IPacienteRepository> _pacienteRepositoryMock;
        private readonly Mock<IConsultaRepository> _consultaRepositoryMock;

        // O Service é quem queremos testar de verdade
        private readonly PacienteService _pacienteService;

        public PacienteServiceTests()
        {
            // 1. Preparamos o cenário
            _pacienteRepositoryMock = new Mock<IPacienteRepository>();
            _consultaRepositoryMock = new Mock<IConsultaRepository>();

            // Injetamos o repositório falso dentro do serviço
            _pacienteService = new PacienteService(_pacienteRepositoryMock.Object, _consultaRepositoryMock.Object);
        }

        [Fact] // [Fact] significa que isso é um teste que deve ser rodado
        public async Task CadastrarPaciente_DeveRetornarSucesso_QuandoDadosForemValidos()
        {
            // ARRANGE (Preparação)
            // Criamos os dados que vamos enviar (o DTO)
            var dto = new CreatePacienteDTO
            {
                Nome = "Teste Unitário",
                CPF = "111.111.111-11",
                ValorConsulta = 100
            };

            // Ensinamos o Mock: "Quando alguém chamar o método CriarAsync, retorne um Paciente com ID 1"
            _pacienteRepositoryMock.Setup(x => x.CriarAsync(It.IsAny<Paciente>()))
                .ReturnsAsync((Paciente p) =>
                {
                    // EF generates ID; no need to set Id in mock
                    return p;
                });

            // ACT (Ação)
            // Executamos o método que queremos testar
            var resultado = await _pacienteService.CadastrarPacienteAsync(dto);

            // ASSERT (Verificação) (utilizando FluentAssertions)
            // Verificamos se o resultado foi o esperado
            resultado.Should().NotBeNull(); // Não pode ser nulo

            // ID generated by DB; verify through repository or service
            // No assertion on Id value needed
            resultado.Nome.Should().Be(dto.Nome); // O nome deve ser o mesmo que enviamos

            // Verificamos se o Service realmente chamou o Repositório 1 vez
            _pacienteRepositoryMock.Verify(x => x.CriarAsync(It.IsAny<Paciente>()), Times.Once);
        }

        [Fact]
        public async Task CadastrarPaciente_DeveLancarErro_QuandoValorForNegativo()
        {
            // ARRANGE
            var dto = new CreatePacienteDTO
            {
                Nome = "Teste Negativo",
                CPF = "111.111.111-11",
                ValorConsulta = -50 // Valor inválido
            };

            // Act
            Func<Task> action = async () => await _pacienteService.CadastrarPacienteAsync(dto);

            // Assert: Verifica se a excepção específica de Domínio (ArgumentException) foi lançada
            await action.Should().ThrowAsync<ArgumentException>()
                .WithMessage("*O valor da consulta não pode ser negativo.*");
        }
    }
}